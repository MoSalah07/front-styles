/**
 * Generates src/index.ts from whatever lives in src/components, src/blocks,
 * src/templates and src/hooks.
 *
 * The barrel is generated rather than hand-edited so that several people (or
 * agents) can add components in parallel without every one of them touching the
 * same file and conflicting. Run it after adding or removing a component;
 * `pnpm build` runs it automatically.
 */
import { readdirSync, existsSync, writeFileSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src");
// Hooks are plain .ts; everything else is .tsx. They are in the barrel too, so
// an app installing from npm can build its own controls on useTheme and
// useLocale without reaching past the package root.
const DIRS = [
  { name: "components", ext: ".tsx" },
  { name: "blocks", ext: ".tsx" },
  { name: "templates", ext: ".tsx" },
  { name: "hooks", ext: ".ts" },
];

/** Collects every exported binding and type from a source file. */
function exportsOf(source) {
  const values = new Set();
  const types = new Set();

  // export { A, B, type C }  and  export type { A, B }
  // The `type` keyword may sit outside the braces, in which case every name in
  // the list is a type. Missing that case exports a type as a value and breaks
  // the build at the import site.
  // The trailing `from "..."` is optional so that a re-export barrel of its
  // own — lib/i18n.tsx forwards the catalogues it sits on — is read too.
  for (const m of source.matchAll(
    /export\s+(type\s+)?\{([^}]*)\}\s*(?:from\s*["'][^"']+["']\s*)?;/g,
  )) {
    const allTypes = Boolean(m[1]);
    for (const raw of m[2].split(",")) {
      const part = raw.trim();
      if (!part) continue;
      const isType = allTypes || /^type\s+/.test(part);
      const name = part
        .replace(/^type\s+/, "")
        .split(/\s+as\s+/)
        .pop()
        .trim();
      if (!name) continue;
      (isType ? types : values).add(name);
    }
  }
  // export function / const / class
  for (const m of source.matchAll(
    /export\s+(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z0-9_$]+)/g,
  )) {
    values.add(m[1]);
  }
  // export interface / type / enum
  for (const m of source.matchAll(/export\s+(?:interface|type|enum)\s+([A-Za-z0-9_$]+)/g)) {
    types.add(m[1]);
  }
  for (const t of types) values.delete(t);
  return { values: [...values].sort(), types: [...types].sort() };
}

/**
 * One `export { ... } from "..."` statement, already wrapped the way Prettier
 * would wrap it at a printWidth of 100. Without that the generated file comes
 * out dirty and `pnpm build && pnpm format:check` can never both pass.
 */
function exportLine(specifiers, from) {
  const oneLine = `export { ${specifiers.join(", ")} } from "${from}";`;
  if (oneLine.length <= 100) return oneLine;
  return [`export {`, ...specifiers.map((s) => `  ${s},`), `} from "${from}";`].join("\n");
}

const lines = [
  "// GENERATED by scripts/gen-barrel.mjs — do not edit by hand.",
  "// Add a file under src/components, src/blocks, src/templates or src/hooks and rebuild.",
  "",
];

// lib/ is listed rather than scanned: it also holds the message catalogues and
// their types, which are reached through i18n.tsx and must not each become a
// top-level export of the package.
const LIB = ["lib/cn.ts", "lib/i18n.tsx"];

for (const rel of LIB) {
  const { values, types } = exportsOf(readFileSync(join(src, rel), "utf8"));
  const from = `./${rel.replace(/\.tsx?$/, "")}`;
  lines.push(exportLine([...values, ...types.map((t) => `type ${t}`)], from));
}

let count = 0;
for (const { name: dir, ext } of DIRS) {
  const abs = join(src, dir);
  if (!existsSync(abs)) continue;
  const files = readdirSync(abs)
    .filter((f) => f.endsWith(ext) && !f.includes(".test.") && !f.includes(".stories."))
    .sort();
  if (!files.length) continue;

  lines.push("", `// ${dir}`);
  for (const file of files) {
    const name = file.slice(0, -ext.length);
    const { values, types } = exportsOf(readFileSync(join(abs, file), "utf8"));
    if (!values.length && !types.length) continue;
    const specifiers = [...values, ...types.map((t) => `type ${t}`)];
    lines.push(exportLine(specifiers, `./${dir}/${name}`));
    count++;
  }
}

writeFileSync(join(src, "index.ts"), lines.join("\n") + "\n");
console.log(`barrel: ${count} modules -> src/index.ts`);
